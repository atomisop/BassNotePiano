/**
 * Uploads the homepage's scroll-video assets to R2.
 *
 * These are large, immutable, and served on every visit, exactly the profile
 * object storage exists for, and exactly the wrong thing to keep in git, where
 * 31MB would be permanent history on every clone and every deploy.
 *
 * Run with:  npm run upload:media
 *
 * Safe to re-run. Keys are content-addressed by a short hash of the file, so
 * a re-upload of unchanged bytes overwrites itself and a changed file lands on
 * a new key, which is what makes the immutable cache header below honest.
 * Nothing is deleted; old keys simply stop being referenced.
 */

import { createHash } from "node:crypto";
import { readFile, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { config } from "dotenv";
import { S3Client, PutObjectCommand } from "@aws-sdk/client-s3";

config();

const REQUIRED = [
  "R2_ACCOUNT_ID",
  "R2_ACCESS_KEY_ID",
  "R2_SECRET_ACCESS_KEY",
  "R2_BUCKET_NAME",
  "R2_PUBLIC_URL",
] as const;

const ASSETS = [
  { file: "studio.mp4", contentType: "video/mp4" },
  { file: "studio-mobile.mp4", contentType: "video/mp4" },
  { file: "studio-poster.jpg", contentType: "image/jpeg" },
];

const LOCAL_DIR = join(process.cwd(), "public", "video");

function requireEnv() {
  const missing = REQUIRED.filter((k) => !process.env[k]);
  if (missing.length) {
    console.error(
      `\nObject storage isn't configured. Missing in .env:\n` +
        missing.map((k) => `  - ${k}`).join("\n") +
        `\n\nSee .env.example for where each value comes from in the Cloudflare dashboard.\n`,
    );
    process.exit(1);
  }
}

function client() {
  return new S3Client({
    region: "auto",
    endpoint: `https://${process.env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
    credentials: {
      accessKeyId: process.env.R2_ACCESS_KEY_ID!,
      secretAccessKey: process.env.R2_SECRET_ACCESS_KEY!,
    },
  });
}

async function main() {
  requireEnv();
  const s3 = client();
  const base = process.env.R2_PUBLIC_URL!.replace(/\/$/, "");
  const results: { file: string; url: string; mb: string }[] = [];

  for (const asset of ASSETS) {
    const path = join(LOCAL_DIR, asset.file);
    const [body, info] = await Promise.all([readFile(path), stat(path)]);

    // Short content hash in the key. Two things fall out of this: re-running
    // with unchanged files is a no-op overwrite, and any future re-encode gets
    // a fresh URL instead of fighting a year-long cache on the CDN edge.
    const hash = createHash("sha256").update(body).digest("hex").slice(0, 10);
    const dot = asset.file.lastIndexOf(".");
    const key = `marketing/${asset.file.slice(0, dot)}.${hash}${asset.file.slice(dot)}`;

    process.stdout.write(`  uploading ${asset.file} (${(info.size / 1_048_576).toFixed(1)}MB)… `);
    await s3.send(
      new PutObjectCommand({
        Bucket: process.env.R2_BUCKET_NAME,
        Key: key,
        Body: body,
        ContentType: asset.contentType,
        // Immutable is only safe because the key carries the content hash.
        CacheControl: "public, max-age=31536000, immutable",
      }),
    );
    console.log("done");
    results.push({ file: asset.file, url: `${base}/${key}`, mb: (info.size / 1_048_576).toFixed(1) });
  }

  console.log("\nUploaded:\n");
  for (const r of results) console.log(`  ${r.file.padEnd(20)} ${r.mb.padStart(5)}MB  ${r.url}`);

  // Write the resolved URLs to a committed manifest rather than reconstructing
  // them at runtime. The keys carry a content hash, so they are not guessable,
  // and putting them here instead of in NEXT_PUBLIC_* means no environment
  // variable has to be kept in sync across .env, Netlify, and any future host.
  // The file is tiny, it is plain data, and the URLs are public by definition.
  const byFile = Object.fromEntries(results.map((r) => [r.file, r.url]));
  const manifest = `// GENERATED by \`npm run upload:media\`, do not edit by hand.
//
// Remote URLs for the homepage scroll-video assets, hosted on R2 so that ~31MB
// of binary never enters git history. Each key carries a content hash, so these
// URLs are safe to cache immutably and a re-encode always produces a new one.
//
// Empty strings mean "not uploaded yet", <ScrollVideoBackground> then falls
// back to the local /video/* copies, so the page works either way.
export const MEDIA = {
  video: ${JSON.stringify(byFile["studio.mp4"] ?? "")},
  videoMobile: ${JSON.stringify(byFile["studio-mobile.mp4"] ?? "")},
  poster: ${JSON.stringify(byFile["studio-poster.jpg"] ?? "")},
} as const;
`;
  const manifestPath = join(process.cwd(), "src", "lib", "media-manifest.ts");
  await writeFile(manifestPath, manifest, "utf8");
  console.log(`\nWrote src/lib/media-manifest.ts, commit it, then the site serves from R2.`);
  console.log(`Once verified you can delete public/video/ (it is gitignored).\n`);
}

main().catch((err) => {
  console.error("\nUpload failed:", err instanceof Error ? err.message : err);
  process.exit(1);
});
