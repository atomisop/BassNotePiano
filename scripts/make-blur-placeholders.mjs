// Makes a BlurHash (a ~30 character string) for each image in public/, written to
// src/lib/blurPlaceholders.generated.ts. Run after adding or changing a photo:  node scripts/make-blur-placeholders.mjs
// <BlurhashImage> draws the hash as a soft version of the picture's own colours until the real photo has loaded.
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { encode } from "blurhash";

const root = path.resolve("public");
const folders = ["marketing", "shop", "screenshots"];
const out = {};

for (const folder of folders) {
  for (const file of await readdir(path.join(root, folder))) {
    if (!/\.(jpe?g|png|webp)$/i.test(file)) continue;
    const { data, info } = await sharp(path.join(root, folder, file)).resize(32, 32, { fit: "inside" }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const hash = encode(new Uint8ClampedArray(data), info.width, info.height, 4, 3);
    out[`/${folder}/${file}`] = hash;
  }
}

const body =
  "// Generated by scripts/make-blur-placeholders.mjs. Do not edit by hand.\n" +
  "export const BLUR_PLACEHOLDERS: Record<string, string> = " +
  JSON.stringify(out, null, 2) +
  ";\n";
await writeFile(path.resolve("src/lib/blurPlaceholders.generated.ts"), body);
console.log(`Wrote ${Object.keys(out).length} placeholders.`);
